#!/usr/bin/env node
/**
 * Regenerate each product Skill's `references/operations.md` from two authorities:
 *  - the published OpenAPI document (paths and operation IDs), and
 *  - the published CLI manifest (`sinecloud api list --json`), which carries scopes and commands.
 *
 * A Skill must never hardcode an operation. If the two authorities disagree, this script fails
 * instead of publishing a guess.
 */
import { execFile } from 'node:child_process'
import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { promisify } from 'node:util'

const run = promisify(execFile)
const root = path.resolve(import.meta.dirname, '..')
const check = process.argv.includes('--check')
const origin = (process.env.SINECLOUD_OPENAPI_ORIGIN ?? 'https://sinecloud.dev').replace(/\/$/, '')
const products = ['agents', 'box', 'powers', 'gateway']
const bin = path.join(root, 'node_modules', '.bin', process.platform === 'win32' ? 'sinecloud.cmd' : 'sinecloud')

if (!existsSync(bin)) {
  console.error('The CLI is not installed. Run: npm install')
  process.exit(1)
}

const httpMethods = new Set(['get', 'post', 'put', 'patch', 'delete'])
const stale = []

function operationIndex(document) {
  const index = new Map()
  for (const [route, item] of Object.entries(document.paths ?? {})) {
    for (const [method, operation] of Object.entries(item ?? {})) {
      if (!httpMethods.has(method) || !operation?.operationId) continue
      index.set(operation.operationId, { method: method.toUpperCase(), path: route })
    }
  }
  return index
}

function areaOf(route, product) {
  const rest = route.replace(new RegExp(`^/api/${product}/v1/?`), '')
  const first = rest.split('/').filter(Boolean)[0] ?? ''
  return first.startsWith('{') || !first ? 'root' : first
}

function render(product, manifest, index) {
  const rows = manifest.map(entry => {
    const contract = index.get(entry.operationId)
    if (!contract) {
      throw new Error(`${product}: CLI operation "${entry.operationId}" is not in the published OpenAPI. Publish the contract first.`)
    }
    return {
      operationId: entry.operationId,
      command: `sinecloud ${entry.command.join(' ')}`,
      scopes: entry.scopes?.length ? entry.scopes : ['—'],
      method: contract.method,
      path: contract.path,
      area: areaOf(contract.path, product),
    }
  }).sort((left, right) => left.area.localeCompare(right.area) || left.path.localeCompare(right.path) || left.method.localeCompare(right.method))

  const scopes = [...new Set(rows.flatMap(row => row.scopes))].sort()
  const lines = [
    '<!-- Generated by scripts/generate-operations.mjs. Do not edit by hand. -->',
    `# ${product[0].toUpperCase()}${product.slice(1)} operations`,
    '',
    `Authorities: [\`${origin}/api/openapi/${product}.json\`](${origin}/api/openapi/${product}.json) and \`sinecloud api list --product ${product} --json\`.`,
    `Scopes in use: ${scopes.map(scope => `\`${scope}\``).join(', ')}.`,
    'The CLI inserts the selected workspace and resource IDs into the path; raw HTTP uses the published path below.',
    '',
    '| Area | Operation | Scope | CLI | HTTP |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map(row => `| ${row.area} | \`${row.operationId}\` | ${row.scopes.map(scope => `\`${scope}\``).join(', ')} | \`${row.command}\` | \`${row.method} ${row.path}\` |`),
    '',
    `Total: ${rows.length} operations.`,
    '',
  ]
  return lines.join('\n')
}

for (const product of products) {
  const [{ stdout }, response] = await Promise.all([
    run(bin, ['api', 'list', '--product', product, '--json'], { cwd: root, maxBuffer: 8 * 1024 * 1024 }),
    fetch(`${origin}/api/openapi/${product}.json`),
  ])
  if (!response.ok) throw new Error(`${product}: OpenAPI ${response.status} from ${origin}`)
  const manifest = JSON.parse(stdout)
  const index = operationIndex(await response.json())
  const content = render(product, manifest, index)
  const target = path.join(root, 'skills', `sinecloud-${product}`, 'references', 'operations.md')

  if (check) {
    const current = existsSync(target) ? await readFile(target, 'utf8') : ''
    if (current !== content) stale.push(path.relative(root, target))
    continue
  }
  await writeFile(target, content)
  console.log(`${path.relative(root, target)}: ${manifest.length} operations`)
}

if (check && stale.length) {
  console.error(`Generated operation tables are out of date:\n${stale.map(file => `  ${file}`).join('\n')}\nRun: npm run generate`)
  process.exit(1)
}
if (check) console.log('Generated operation tables match the published contract.')
